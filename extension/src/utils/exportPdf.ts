import jsPDF from "jspdf";

/**
 * Very simple markdown stripper so PDF doesn't look messy.
 */
function stripMarkdown(s: string) {
  return (s || "")
    .replace(/```[\s\S]*?```/g, "")
    .replace(/[#>*_`]/g, "")
    .replace(/\r/g, "")
    .trim();
}

function safeFileName(s: string) {
  return (s || "data-lawyer-report")
    .toLowerCase()
    .replace(/https?:\/\//g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/-+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export function exportAnalysisToPDF(analysis: any) {
  const doc = new jsPDF({ unit: "pt", format: "a4" });

  const left = 48;
  const width = 520;
  let y = 56;

  const site =
    analysis?.service_name ||
    analysis?.structured?.site ||
    analysis?.structured?.controller_hint ||
    "Unknown Site";

  const url = analysis?.url || "";
  const riskLevel = analysis?.risk_level || "UNKNOWN";
  const riskScore = analysis?.risk_score ?? "-";
  const jurisdiction = analysis?.jurisdiction || analysis?.structured?.jurisdiction || "UNKNOWN";

  const createdAt =
    analysis?.saved_at ||
    new Date().toISOString();

  const redFlags: string[] = Array.isArray(analysis?.red_flags) ? analysis.red_flags : [];
  const summaryText = stripMarkdown(String(analysis?.summary || ""));

  // ============ Helpers ============
  function addPageIfNeeded(extra: number = 0) {
    if (y + extra > 780) {
      doc.addPage();
      y = 56;
    }
  }

  function writeHeading(text: string) {
    addPageIfNeeded(30);
    doc.setFont("helvetica", "bold");
    doc.setFontSize(13);
    doc.text(text, left, y);
    y += 18;
  }

  function writeBody(text: string) {
    doc.setFont("helvetica", "normal");
    doc.setFontSize(11);

    const lines = doc.splitTextToSize(text, width);
    for (const line of lines) {
      addPageIfNeeded(18);
      doc.text(line, left, y);
      y += 14;
    }
    y += 6;
  }

  // ============ Title ============
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text("Data Lawyer — Policy Analysis Report", left, y);
  y += 26;

  doc.setFont("helvetica", "normal");
  doc.setFontSize(11);
  doc.text(`Site: ${site}`, left, y);
  y += 16;

  if (url) {
    const urlLines = doc.splitTextToSize(`URL: ${url}`, width);
    doc.text(urlLines, left, y);
    y += urlLines.length * 14 + 2;
  }

  doc.text(`Risk Level: ${riskLevel}`, left, y);
  y += 16;

  doc.text(`Risk Score: ${riskScore}/100`, left, y);
  y += 16;

  doc.text(`Jurisdiction: ${jurisdiction}`, left, y);
  y += 16;

  doc.text(`Generated: ${createdAt}`, left, y);
  y += 26;

  // ============ Red Flags ============
  writeHeading("Red Flags");

  if (!redFlags.length) {
    writeBody("- None detected");
  } else {
    for (const flag of redFlags.slice(0, 12)) {
      writeBody(`- ${flag}`);
    }
  }

  // ============ Summary ============
  writeHeading("Summary");

  if (!summaryText) {
    writeBody("No summary available.");
  } else {
    writeBody(summaryText);
  }

  // ============ Footer ============
  addPageIfNeeded(40);
  doc.setFont("helvetica", "italic");
  doc.setFontSize(9);
  doc.text(
    "Generated by Data Lawyer (Public Beta). This is not legal advice.",
    left,
    820
  );

  // Download
  const fileName = `${safeFileName(site)}-data-lawyer-report.pdf`;
  doc.save(fileName);
}
